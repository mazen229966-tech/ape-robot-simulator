"""Verify robot/urdf/sv2_6045.urdf reproduces the DH kinematics exactly.

The URDF is generated by ``tools/generate_urdf.py``; this test parses the
file and recomputes forward kinematics independently of the simulator.
"""
from __future__ import annotations

import math
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

from app.models.ape_sv45 import DH_TABLE_EDUCATIONAL
from app.robotics import dh as dhm

URDF_PATH = Path(__file__).resolve().parents[2] / "robot" / "urdf" / "sv2_6045.urdf"


def _rx(a: float) -> np.ndarray:
    c, s = math.cos(a), math.sin(a)
    return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])


def _ry(a: float) -> np.ndarray:
    c, s = math.cos(a), math.sin(a)
    return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])


def _rz(a: float) -> np.ndarray:
    c, s = math.cos(a), math.sin(a)
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])


def _rot_z(a: float) -> np.ndarray:
    T = np.eye(4)
    T[:3, :3] = _rz(a)
    return T


def _origin_T(el) -> np.ndarray:
    o = el.find("origin")
    xyz = np.array([float(v) for v in o.get("xyz").split()])
    r, p, y = (float(v) for v in o.get("rpy").split())
    T = np.eye(4)
    T[:3, :3] = _rz(y) @ _ry(p) @ _rx(r)
    T[:3, 3] = xyz
    return T


def test_urdf_matches_dh_kinematics() -> None:
    assert URDF_PATH.exists(), f"missing {URDF_PATH} — run tools/generate_urdf.py"

    joints = [j for j in ET.parse(URDF_PATH).getroot() if j.tag == "joint"]
    revolute = [j for j in joints if j.get("type") == "revolute"]
    tool_joint = next(j for j in joints if j.get("name") == "tool_joint")
    assert [j.get("name") for j in revolute] == [f"joint{i}" for i in range(1, 7)]

    def urdf_fk(q: np.ndarray) -> np.ndarray:
        T = np.eye(4)
        for j, qi in zip(revolute, q):
            T = T @ _origin_T(j) @ _rot_z(qi)
        return T @ _origin_T(tool_joint)

    rng = np.random.default_rng(7)
    for _ in range(200):
        q = rng.uniform(-3.0, 3.0, 6)
        T_dh = np.eye(4)
        for i, (_, d, a, alpha) in enumerate(DH_TABLE_EDUCATIONAL):
            T_dh = T_dh @ dhm.dh_transform(float(q[i]), d, a, alpha)
        assert np.allclose(urdf_fk(q), T_dh, atol=1e-8), "URDF diverged from DH"
